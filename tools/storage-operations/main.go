// Generates both protocol definitions from operations.json. Run from repository root.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
)

type operation struct {
	Name      string
	Control   bool
	Publishes bool
}

func main() {
	check := flag.Bool("check", false, "reject generated file drift without writing")
	flag.Parse()
	raw, err := os.ReadFile("tools/storage-operations/operations.json")
	must(err)
	var ops []operation
	must(json.Unmarshal(raw, &ops))
	var g, s strings.Builder
	g.WriteString("// Code generated by tools/storage-operations; DO NOT EDIT.\npackage localstore\n\n// Operation is a snapshot request operation, distinct from runtime-secret and transfer framing operations.\ntype Operation string\n\nconst (\n")
	s.WriteString("// Code generated by tools/storage-operations; DO NOT EDIT.\nimport Foundation\n\nenum StorageOperation: String, Codable, CaseIterable {\n")
	seen := map[string]bool{}
	for _, op := range ops {
		if !regexp.MustCompile(`^[a-z][A-Za-z]+$`).MatchString(op.Name) || seen[op.Name] || (op.Control && op.Publishes) {
			panic("invalid operation schema")
		}
		seen[op.Name] = true
		fmt.Fprintf(&g, "Operation%s Operation = %q\n", strings.ToUpper(op.Name[:1])+op.Name[1:], op.Name)
		fmt.Fprintf(&s, "    case %s\n", op.Name)
	}
	g.WriteString(")\n\n")
	for _, property := range []string{"Valid", "PublishesCredentials", "AllowsTransfer"} {
		fmt.Fprintf(&g, "func (o Operation) %s() bool {\nswitch o {\n", property)
		for _, op := range ops {
			if property == "Valid" || property == "PublishesCredentials" && op.Publishes || property == "AllowsTransfer" && !op.Control {
				fmt.Fprintf(&g, "case Operation%s: return true\n", strings.ToUpper(op.Name[:1])+op.Name[1:])
			}
		}
		g.WriteString("default: return false\n}\n}\n")
	}
	s.WriteString("\n    var allowsTransfer: Bool {\n        switch self {\n")
	for _, op := range ops {
		fmt.Fprintf(&s, "        case .%s: return %t\n", op.Name, !op.Control)
	}
	s.WriteString("        }\n    }\n}\n")
	formatted, err := format.Source([]byte(g.String()))
	must(err)
	for path, data := range map[string][]byte{"internal/localstore/operations_generated.go": formatted, "macos/Bridge/StorageOperation.generated.swift": []byte(s.String())} {
		if *check {
			existing, err := os.ReadFile(path)
			must(err)
			if !bytes.Equal(existing, data) {
				panic("generated file drift: " + path)
			}
		} else {
			must(os.WriteFile(path, data, 0644))
		}
	}
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
